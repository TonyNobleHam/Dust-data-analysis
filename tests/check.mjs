import { readFileSync, readdirSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);
for (const script of scripts) new vm.Script(script);
const nodes = new Map();
const node = () => ({value:'0', style:{}, classList:{add(){},remove(){},toggle(){}}, addEventListener(){}, appendChild(){}, click(){}});
const get = id => { if(!nodes.has(id)) nodes.set(id,node()); return nodes.get(id); };
const context = vm.createContext({document:{getElementById:get,createElement:node,querySelectorAll:()=>[]}, console, setTimeout, clearTimeout, alert(){}});
vm.runInContext(scripts[1], context);
const fixture = readFileSync(new URL('./sample.csv',import.meta.url),'utf8');
context.fixture = fixture;
vm.runInContext("parseCSV(fixture,{name:'sample.csv',size:fixture.length})",context);
assert.equal(vm.runInContext('allData.length',context),4);
assert.equal(vm.runInContext('Object.keys(sessions).length',context),2);
assert.equal(vm.runInContext('sessions[1].reduce((sum,d)=>sum+d.pm25,0)/sessions[1].length',context),20);
assert.throws(()=>vm.runInContext("parseCSV('invalid',{name:'bad.csv',size:7})",context));
assert.equal(vm.runInContext('allData.length',context),4,'invalid input must preserve prior data');
assert.deepEqual(readdirSync(new URL('../dist/',import.meta.url)).sort(),['404.html','_headers','index.html']);
assert(!/\b(fetch\s*\(|XMLHttpRequest|sendBeacon\s*\(|WebSocket\s*\()/.test(html));
console.log('PASS: JavaScript syntax, synthetic CSV parsing, two sessions, PM2.5 mean, invalid-input preservation, deployment allowlist, network API scan. Browser UI NOT tested.');
